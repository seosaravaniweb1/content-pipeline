BY_KEY: dict[str, Preset] = {preset.key: preset for preset in PRESETS}
BY_LABEL: dict[str, Preset] = {preset.label: preset for preset in PRESETS}


def resolve(names: object) -> list[Preset]:
    """نام‌ها (کلید یا برچسب فارسی) → دسته‌ها. نام ناشناخته نادیده نمی‌رود؛
    به‌عنوان دسته‌ی سفارشی بدون نمونه‌عنوان برمی‌گردد تا کاربر بتواند
    موضوع دلخواه خودش را هم بدهد."""
    if not names:
        return []
    if isinstance(names, str):
        names = [names]
    out: list[Preset] = []
    seen: set[str] = set()
    for name in names:  # type: ignore[union-attr]
        text = str(name).strip()
        if not text:
            continue
        preset = BY_KEY.get(text) or BY_LABEL.get(text)
        if preset is None:
            preset = Preset(key=f"custom:{text}", label=text, hint="دسته‌ی سفارشی")
        if preset.key in seen:
            continue
        seen.add(preset.key)
        out.append(preset)
    return out


def as_dicts() -> list[dict]:
    return [
        {"key": p.key, "label": p.label, "hint": p.hint, "examples": list(p.examples)}
        for p in PRESETS
    ]


